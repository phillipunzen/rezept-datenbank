import {test, expect} from "@playwright/test";
import {emptyRecipe} from "../../shared/recipes";
test("cookbooks, planner, shared shopping and history connect to full recipe pages", async ({page}) => {
 test.setTimeout(60000);
 const errors:string[]=[]; page.on("pageerror",e=>errors.push(e.message));
 await page.goto("/");
 await page.getByLabel("E-Mail-Adresse",{exact:true}).fill("browser@example.test");
 await page.getByLabel("Passwort",{exact:true}).fill("browser-test-password-long");
 await page.getByRole("button",{name:"Anmelden",exact:true}).click();
 await expect(page.getByRole("heading",{name:"Your recipes",exact:true})).toBeVisible();
 const recipe = await page.evaluate(async (draft) => {
  const householdId=(await (await fetch("/api/v1/households")).json()).households[0].household.id;
  const r=await fetch("/api/v1/recipes",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify({...draft,householdId})});
  if(!r.ok) throw new Error(await r.text()); return (await r.json()).recipe;
 }, {...emptyRecipe(""),title:"Planning potatoes",ingredients:[{name:"Kartoffeln",amount:"500",unit:"g",group:"",note:""}],steps:[{instruction:"Boil",durationSeconds:null}]});
 const nav=page.getByRole("navigation",{name:"Navigation",exact:true});
 await nav.getByRole("button",{name:"Cookbooks",exact:true}).click();
 const creation=page.locator(".collection-sidebar form");
 await creation.getByLabel("Name",{exact:true}).fill("Weeknight meals");
 await creation.getByLabel("Description",{exact:true}).fill("Family collection");
 await creation.getByRole("button",{name:"Create",exact:true}).click();
 await expect(page.locator(".collection-content h2")).toHaveText("Weeknight meals");
 const addBook=page.locator(".collection-content .inline-resource-form");
 await addBook.getByRole("combobox",{name:"Recipe",exact:true}).selectOption(recipe.id);
 await addBook.getByRole("button",{name:"Add recipe",exact:true}).click();
 await expect(page.locator(".reference-card")).toHaveCount(1);
 await page.locator(".reference-open").click();
 await expect(page.getByRole("heading",{name:recipe.title,exact:true})).toBeVisible();
 await expect(page.locator(".recipe-library")).toBeHidden();
 await page.getByRole("button",{name:"Add to shopping list",exact:true}).click();
 const recipeShopping=page.locator(".recipe-shopping form");
 await recipeShopping.getByLabel("Name",{exact:true}).fill("Weekend shop");
 await recipeShopping.getByLabel("Servings",{exact:true}).fill("6");
 await recipeShopping.getByRole("button",{name:"Add to shopping list",exact:true}).click();
 await expect(recipeShopping.getByRole("status")).toHaveText("Saved.");
 await nav.getByRole("button",{name:"Shopping list",exact:true}).click();
 await expect(page.locator(".shopping-quantity")).toHaveText("750 g");
 await page.getByLabel("Kartoffeln Done",{exact:true}).check();
 await expect(page.locator(".shopping-row")).toHaveClass(/is-checked/);
 const itemForm=page.locator(".shopping-item-form");
 await itemForm.getByLabel("Ingredient",{exact:true}).fill("Kartoffeln");
 await itemForm.getByLabel("Amount",{exact:true}).fill("0.5");
 await itemForm.getByLabel("Unit",{exact:true}).fill("kg");
 await itemForm.getByRole("button",{name:"Add item",exact:true}).click();
 await expect(page.locator(".shopping-row")).toHaveCount(2);
 await nav.getByRole("button",{name:"Meal planner",exact:true}).click();
 await page.locator(".planner-toolbar").getByLabel("Date",{exact:true}).fill("2026-10-02");
 const planForm=page.locator(".planning-entry-form");
 await planForm.getByRole("combobox",{name:"Recipe",exact:true}).selectOption(recipe.id);
 await planForm.getByLabel("Date",{exact:true}).fill("2026-10-02");
 await planForm.getByLabel("Servings",{exact:true}).fill("6");
 await planForm.getByRole("button",{name:"Plan a meal",exact:true}).click();
 await expect(page.locator(".meal-card")).toHaveCount(1);
 const target=page.locator('.meal-slot[data-date="2026-10-03"][data-slot="LUNCH"]');
 await page.locator(".meal-card").dragTo(target);
 await expect(target.locator(".meal-card")).toHaveCount(1);
 const planShopping=page.locator(".plan-shopping form");
 await planShopping.getByRole("combobox",{name:"Shopping list",exact:true}).selectOption({label:"Weekend shop"});
 const response=page.waitForResponse(r=>r.url().endsWith("/from-plan")&&r.request().method()==="POST");
 await planShopping.getByRole("button",{name:"Add to shopping list",exact:true}).click();
 expect((await response).ok()).toBe(true);
 await nav.getByRole("button",{name:"Shopping list",exact:true}).click();
 await expect(page.locator(".shopping-row:not(.is-checked) .shopping-quantity")).toHaveText("1.25 kg");
 const tab=await page.context().newPage();
 await tab.goto("/");
 await tab.getByRole("navigation",{name:"Navigation",exact:true}).getByRole("button",{name:"Shopping list",exact:true}).click();
 await expect(tab.locator(".shopping-row")).toHaveCount(2);
 await page.locator(".shopping-row:not(.is-checked)").getByLabel("Kartoffeln Done",{exact:true}).check();
 await expect(tab.locator(".shopping-row.is-checked")).toHaveCount(2,{timeout:15000});
 await tab.close();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole("navigation",{name:"Mobile Navigation",exact:true}).getByRole("button",{name:"Meal planner",exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:"test-results/planner-mobile.png",fullPage:true});
 const cleaned=await page.evaluate(async recipe=> (await fetch(`/api/v1/recipes/${recipe.id}?revision=${recipe.revision}`,{method:"DELETE"})).ok,recipe);
 expect(cleaned).toBe(true); expect(errors).toEqual([]);
});
